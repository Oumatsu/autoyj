import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const targetArgIndex = process.argv.indexOf("--target");
const targetPath = targetArgIndex >= 0 ? process.argv[targetArgIndex + 1] : ".dev.vars.local";
const trackedDevVarsWarning =
  targetPath === ".dev.vars"
    ? "Warning: .dev.vars is tracked in this repository. Do not commit secret changes."
    : "";

const portalKeys = [
  "FEISHU_BASE_APP_TOKEN",
  "FEISHU_TABLE_CUSTOMERS",
  "FEISHU_TABLE_VEHICLES",
  "FEISHU_TABLE_INQUIRIES",
  "FEISHU_TABLE_QUOTES",
  "FEISHU_TABLE_NEGOTIATIONS",
  "FEISHU_TABLE_ORDERS",
  "PORTAL_COOKIE_NAME",
];

function runLarkCli(args) {
  const command =
    process.platform === "win32"
      ? "powershell.exe"
      : process.env.LARK_CLI_BIN || "lark-cli";
  const commandArgs =
    process.platform === "win32"
      ? [
          "-NoProfile",
          "-ExecutionPolicy",
          "Bypass",
          "-File",
          process.env.LARK_CLI_BIN || join(process.env.APPDATA || "", "npm", "lark-cli.ps1"),
          ...args,
        ]
      : args;

  return execFileSync(command, commandArgs, {
    cwd: process.cwd(),
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
}

function parseFirstJson(output) {
  const start = output.indexOf("{");
  const end = output.lastIndexOf("}");
  if (start === -1 || end === -1) {
    throw new Error(`Expected JSON output from lark-cli, got:\n${output}`);
  }
  return JSON.parse(output.slice(start, end + 1));
}

function readEnvFile(path) {
  if (!existsSync(path)) return {};
  const lines = readFileSync(path, "utf8").split(/\r?\n/);
  const values = {};
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || !trimmed.includes("=")) continue;
    const index = trimmed.indexOf("=");
    values[trimmed.slice(0, index)] = trimmed.slice(index + 1);
  }
  return values;
}

function writeEnvFile(path, values) {
  const orderedKeys = [
    "BETTER_AUTH_SECRET",
    "BETTER_AUTH_URL",
    "BETTER_AUTH_API_KEY",
    "PASSKEY_RP_ID",
    "FEISHU_APP_ID",
    "FEISHU_APP_SECRET",
    "FEISHU_BASE_APP_TOKEN",
    "FEISHU_TABLE_CUSTOMERS",
    "FEISHU_TABLE_VEHICLES",
    "FEISHU_TABLE_INQUIRIES",
    "FEISHU_TABLE_QUOTES",
    "FEISHU_TABLE_NEGOTIATIONS",
    "FEISHU_TABLE_ORDERS",
    "PORTAL_SESSION_SECRET",
    "PORTAL_COOKIE_NAME",
    "GOOGLE_CLIENT_ID",
    "GOOGLE_CLIENT_SECRET",
    "APPLE_CLIENT_ID",
    "APPLE_CLIENT_SECRET",
    "FACEBOOK_CLIENT_ID",
    "FACEBOOK_CLIENT_SECRET",
    "WECHAT_APP_ID",
    "WECHAT_APP_SECRET",
  ];

  const emitted = new Set();
  const lines = [
    "# Local development secrets. Do not commit this file.",
    "# Generated by npm run sync:feishu-env.",
  ];

  for (const key of orderedKeys) {
    if (!(key in values)) continue;
    emitted.add(key);
    lines.push(`${key}=${values[key] ?? ""}`);
    if (key === "PASSKEY_RP_ID" || key === "PORTAL_COOKIE_NAME") lines.push("");
  }

  for (const [key, value] of Object.entries(values)) {
    if (!emitted.has(key)) lines.push(`${key}=${value ?? ""}`);
  }

  writeFileSync(path, `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`, "utf8");
}

function randomSecret() {
  return randomBytes(48).toString("base64url");
}

const cliConfig = parseFirstJson(runLarkCli(["config", "show"]));
if (!cliConfig.appId) {
  throw new Error("lark-cli config show did not return appId. Run lark-cli config init first.");
}

function isMasked(value) {
  return typeof value === "string" && /^\*+$/.test(value);
}

function pickSecret(cliSecret, sourceSecret) {
  if (typeof cliSecret === "string" && cliSecret && !isMasked(cliSecret)) return cliSecret;
  if (sourceSecret && !isMasked(sourceSecret)) return sourceSecret;
  return "";
}

const existingTarget = readEnvFile(targetPath);
const currentDevVars = readEnvFile(".dev.vars");
const generatedFeishu = readEnvFile(".dev.vars.feishu.example");
const example = readEnvFile(".dev.vars.example");
const source = { ...example, ...generatedFeishu, ...currentDevVars, ...existingTarget };

const next = {
  ...source,
  FEISHU_APP_ID: cliConfig.appId,
  FEISHU_APP_SECRET: pickSecret(cliConfig.appSecret, source.FEISHU_APP_SECRET),
  PORTAL_SESSION_SECRET: source.PORTAL_SESSION_SECRET || randomSecret(),
  PORTAL_COOKIE_NAME: source.PORTAL_COOKIE_NAME || "autoyj_portal",
};

for (const key of portalKeys) {
  if (!next[key] && generatedFeishu[key]) next[key] = generatedFeishu[key];
}

writeEnvFile(targetPath, next);

console.log(`Wrote ${targetPath}`);
if (trackedDevVarsWarning) console.log(trackedDevVarsWarning);
console.log("");
console.log("Resolved values:");
console.log(`  FEISHU_APP_ID=${next.FEISHU_APP_ID}`);
console.log(`  FEISHU_APP_SECRET=${next.FEISHU_APP_SECRET ? "***" : "(missing; lark-cli only exposes a masked appSecret)"}`);
console.log(`  FEISHU_BASE_APP_TOKEN=${next.FEISHU_BASE_APP_TOKEN || "(missing)"}`);
console.log("  PORTAL_SESSION_SECRET=***");
if (!next.FEISHU_APP_SECRET) {
  console.log("");
  console.log("Add the real FEISHU_APP_SECRET from Feishu Developer Console or re-run lark-cli config init with --app-secret-stdin.");
}
console.log("");
console.log("For local Vinext/Cloudflare dev, use:");
console.log("  npm run sync:feishu-env -- --target .dev.vars");
